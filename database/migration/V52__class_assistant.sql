CREATE TABLE IF NOT EXISTS em_teaching_class_assistant (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teaching_class_id bigint NOT NULL,
    user_id bigint NOT NULL,
    creator varchar(128),
    create_time timestamp,
    operator varchar(128),
    update_time timestamp,
    is_deleted boolean NOT NULL DEFAULT false
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_teaching_class_assistant_active
    ON em_teaching_class_assistant (teaching_class_id, user_id)
    WHERE is_deleted = false;

CREATE INDEX IF NOT EXISTS idx_teaching_class_assistant_class
    ON em_teaching_class_assistant (teaching_class_id)
    WHERE is_deleted = false;

CREATE INDEX IF NOT EXISTS idx_teaching_class_assistant_user
    ON em_teaching_class_assistant (user_id)
    WHERE is_deleted = false;

